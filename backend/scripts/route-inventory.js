// Prints the API route inventory (Markdown) for the API Gateway set-up:
//   node backend/scripts/route-inventory.js > docs/API-ROUTES.md
// Reads the router mounts in server.js and the route definitions in routes/*.js
// statically (nothing is started), so it stays in step with the code.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const backend = path.join(here, '..');
const server = fs.readFileSync(path.join(backend, 'server.js'), 'utf8');

// import xRouter from './routes/x.js'   and   import { a as b } from './routes/x.js'
// local name -> { file, name of the router inside that file ('router' for a default export) }
const routerFiles = {};
for (const m of server.matchAll(/import\s+(\w+)\s+from\s+'\.\/routes\/([\w-]+)\.js'/g)) {
  routerFiles[m[1]] = { file: m[2], name: 'router' };
}
for (const m of server.matchAll(/import\s+\{([^}]+)\}\s+from\s+'\.\/routes\/([\w-]+)\.js'/g)) {
  for (const part of m[1].split(',')) {
    const [orig, alias] = part.trim().split(/\s+as\s+/);
    routerFiles[(alias || orig).trim()] = { file: m[2], name: orig.trim() };
  }
}

// app.use('/api/x', ...middleware, xRouter)
const mounts = [];
for (const m of server.matchAll(/^app\.use\(\s*'([^']+)'\s*,(.*)\);\s*$/gm)) {
  const parts = m[2].split(/,(?![^(]*\))/).map((s) => s.trim()).filter(Boolean);
  const routerVar = parts.at(-1);
  if (!routerFiles[routerVar]) continue;
  mounts.push({ base: m[1], mw: parts.slice(0, -1), ...routerFiles[routerVar] });
}

const rows = [];
for (const { base, mw, file, name } of mounts) {
  const src = fs.readFileSync(path.join(backend, 'routes', `${file}.js`), 'utf8');
  const routeDef = new RegExp(String.raw`\b${name}\.(get|post|put|patch|delete)\(\s*(['` + '`' + String.raw`])([^'` + '`' + String.raw`]+)\2\s*,([^\n]*)`, 'g');
  for (const r of src.matchAll(routeDef)) {
    const method = r[1].toUpperCase();
    const sub = r[3] === '/' ? '' : r[3];
    const line = r[4];
    const full = (base + sub).replace(/\/+$/, '') || base;
    const all = [...mw, line].join(' ');
    let auth = 'public';
    if (/requireAdmin|requireAdminUser/.test(all)) auth = 'admin (Bearer JWT)';
    else if (/authenticateToken|requireAuth/.test(all) || /router\.use\(\s*authenticateToken/.test(src)) auth = 'user (Bearer JWT)';
    if (full.startsWith('/api/v1/')) auth = 'user or API client (Bearer JWT, scopes)';
    if (full.startsWith('/api/v1/integrations/erp')) auth = 'ERP API client (Bearer JWT, scopes)';
    if (full === '/api/auth/client-token') auth = 'public (client id + secret)';
    const caller = full.startsWith('/api/v1/') || full === '/api/auth/client-token'
      ? 'system (integration)'
      : full.startsWith('/api/auth/sso/oidc') ? 'browser redirect (DWS Hub)' : 'browser';
    const body = /upload\.|multer/.test(line) || /\/document$/.test(full) && method === 'PUT' ? 'multipart' : method === 'GET' || method === 'DELETE' ? '—' : 'JSON, max 1 MB';
    rows.push({ method, full, auth, caller, body, file });
  }
}

// Health checks are defined in server.js itself.
for (const p of ['/health/live', '/health/ready', '/api/health/live', '/api/health/ready']) {
  rows.push({ method: 'GET', full: p, auth: 'public', caller: 'ALB / API Gateway health check', body: '—', file: 'server.js' });
}

rows.sort((a, b) => a.full.localeCompare(b.full) || a.method.localeCompare(b.method));
const out = [];
out.push('# PM Tool — API route inventory');
out.push('');
out.push('Generated by `node backend/scripts/route-inventory.js` from the code. Base path for everything');
out.push('the API Gateway routes: `/api/`. Auth is a Bearer JWT in the `Authorization` header (no');
out.push('cookies), except the SSO hand-shake, which also uses the short-lived `sso_tx` cookie on');
out.push('`/api/auth/sso` and must be forwarded. Backend timeouts: `/api/v1/integrations/erp/*` 30 s,');
out.push('other `/api/v1/*` 5 s; the rest none.');
out.push('');
out.push('Long or large calls to check against the gateway limits: ERP CR document upload');
out.push('(`PUT /api/v1/integrations/erp/crs/:crId/document`, multipart up to 30 MB), document upload');
out.push('(multipart, 10 MB), project import from Excel (multipart, 5 MB), document download');
out.push('(streams the file, up to 30 MB).');
out.push('');
out.push('| Method | Path | Auth | Caller | Request body | Source |');
out.push('|---|---|---|---|---|---|');
for (const r of rows) out.push(`| ${r.method} | \`${r.full}\` | ${r.auth} | ${r.caller} | ${r.body} | ${r.file} |`);
out.push('');
out.push(`${rows.length} routes.`);
console.log(out.join('\n'));
